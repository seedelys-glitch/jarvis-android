const fs = require("fs");
const s = fs.readFileSync(__dirname + "/../app/src/main/assets/mobile.html", "utf8");
const a = s.indexOf("function lit("), b = s.indexOf("let history =");
const c1 = s.indexOf("function dureeMs("), c2 = s.indexOf("// ---------- commandes ----------");
const store = {};
global.localStorage = { getItem: k => store[k] ?? null, setItem: (k, v) => { store[k] = v; } };
const rappels = [];
global.A = { rappel: (ms, q) => rappels.push([ms, q]), appsTel: t => t === "ouvre spotify" ? "J'ouvre Spotify." : "" };
eval(s.slice(a, b) + s.slice(s.indexOf("function faits()"), s.indexOf("async function chatClaude")) + s.slice(c1, c2) + "; global.competences = competences; global.dureeMs = dureeMs;");
let ok = 0, ko = 0;
const eq = (g, w, what) => { if (g === w) ok++; else { ko++; console.log("RATE", what, ":", JSON.stringify(g), "au lieu de", JSON.stringify(w)); } };
const norm = t => t.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
eq(dureeMs("dans 10 minutes"), 600000, "10 min");
eq(dureeMs("dans une heure et demie"), 5400000, "1 h 30");
eq(dureeMs("minuteur cinq minutes"), 300000, "cinq minutes");
eq(competences(norm("rappelle-moi dans 10 minutes d'appeler le client")), "D'accord, je te le rappelle dans 10 minutes.", "rappel");
eq(rappels[0][1], "appeler le client", "texte du rappel");
eq(competences(norm("minuteur 30 secondes")), "D'accord, je te le rappelle dans 30 secondes.", "minuteur");
eq(competences(norm("rappelle-moi d'appeler maman")).startsWith("Dans combien"), true, "rappel sans durée");
eq(competences(norm("note : acheter du lait")), "C'est noté.", "note");
eq(competences(norm("mes notes")), "Tes dernières notes : acheter du lait.", "mes notes");
eq(competences(norm("retiens que je finis à 18 h")), "C'est retenu.", "retiens");
eq(competences(norm("qu'est-ce que tu sais sur moi")), "Je sais que je finis a 18 h.", "sais sur moi");
eq(competences(norm("oublie que je finis")), "C'est oublié.", "oublie");
eq(competences(norm("mets de la musique")), "J'ouvre Spotify.", "musique");
eq(competences(norm("c'est quoi le prix du gold")), "", "pas une compétence");
eq(competences(norm("rentre à 4000, stop à 4200")), "", "trade : pas une compétence");
console.log(ok + " réussis, " + ko + " ratés");
process.exit(ko ? 1 : 0);
